/* ---- language state ---------------------------------------------------- */
window.Lang = (function () {
  var KEY = "rc.lang";
  var cur = (function () {
    try { return localStorage.getItem(KEY) || window.SITE.defaultLang; }
    catch (e) { return window.SITE.defaultLang; }
  })();

  function get() { return cur; }

  function set(v) {
    cur = (v === "en") ? "en" : "id";
    try { localStorage.setItem(KEY, cur); } catch (e) {}
    document.documentElement.lang = cur;
    document.dispatchEvent(new CustomEvent("langchange", { detail: cur }));
  }

  /* t("nav.home") -> label in the current language */
  function t(key) {
    var d = window.I18N[cur] || window.I18N.id;
    return (key in d) ? d[key] : ((window.I18N.en[key]) || key);
  }

  /* pick({en:"Hello", id:"Halo"}) -> the right one, falling back gracefully.
     Also accepts a plain string, which is returned as-is. */
  function pick(obj) {
    if (obj == null) return "";
    if (typeof obj === "string") return obj;
    return obj[cur] || obj.id || obj.en || "";
  }

  return { get: get, set: set, t: t, pick: pick };
})();
